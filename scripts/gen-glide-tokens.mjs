// Glide palettes → CSS. The three palettes (light, midnight, graphite) live in
// docs/design/glide-tokens.json and nowhere else; this writes them out as
// custom properties so the CSS can never drift from the contract.
//
//   node scripts/gen-glide-tokens.mjs  → src/styles/glide-tokens.css
//
// Scope: the tokens are declared on `.glide` (the site shell and every Glide
// surface) and on `body:has(.glide-page)` (so a Glide page also paints the
// body). They are NOT declared on :root, because the legacy stylesheet already
// uses some of the same names (--surface, --line, --accent, --scrim) with
// other meanings, and every page that has not been restyled yet still reads
// those.
//
// Resolution (see src/lib/theme.ts): <html data-theme="light|dark"
// data-dark="midnight|graphite">. Midnight is the base, Graphite overrides it
// when chosen, Light overrides both. With no data-theme at all (scripting off,
// System choice) prefers-color-scheme decides.
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync('docs/design/glide-tokens.json', 'utf8'));
const SCOPE = ':is(.glide, body:has(.glide-page))';

const block = (name, indent = '  ') =>
    Object.entries(tokens[name])
        .map(([k, v]) => `${indent}--${k}: ${v};`)
        .join('\n');

const css = `/* GENERATED by scripts/gen-glide-tokens.mjs from docs/design/glide-tokens.json.
   Do not edit by hand: change the JSON and run the script. */

/* Midnight: the dark default. */
:where(.glide, body:has(.glide-page)) {
${block('midnight')}
  color-scheme: dark;
}

/* Graphite: the second dark style, chosen in Appearance. */
:root[data-dark='graphite'] ${SCOPE} {
${block('graphite')}
  color-scheme: dark;
}

/* Light: an explicit choice, or System on a light OS (the head script stamps
   data-theme from prefers-color-scheme). */
:root[data-theme='light'] ${SCOPE} {
${block('light')}
  color-scheme: light;
}

/* System with scripting off: no data-theme at all, so the OS decides. */
@media (prefers-color-scheme: light) {
  :root:not([data-theme]) ${SCOPE} {
${block('light', '    ')}
    color-scheme: light;
  }
}
`;

writeFileSync('src/styles/glide-tokens.css', css);
console.log('wrote src/styles/glide-tokens.css', Object.keys(tokens.light).length, 'tokens x', Object.keys(tokens).length, 'palettes');
